import { PI_PACKAGE, type Config } from "./config.ts"
import { Pi2Error, shQuote, shortHash } from "./util.ts"

export const AGENT_DIR = "/opt/pi2/agent"
export const SESSIONS_DIR = "/opt/pi2/sessions"
export const HOME_DIR = "/home/pi2"
export const WORKSPACE_DIR = "/workspace"

export type PackageManager = "apt" | "apk" | "dnf"

export function detectPackageManager(base: string): PackageManager {
  if (/alpine/i.test(base)) return "apk"
  if (/fedora|rhel|centos|rocky|alma|ubi|amazonlinux/i.test(base)) return "dnf"
  return "apt"
}

function installPackages(manager: PackageManager, packages: string[]): string {
  const list = packages.map(shQuote).join(" ")
  switch (manager) {
    case "apt":
      return `apt-get update && DEBIAN_FRONTEND=noninteractive apt-get install -y --no-install-recommends ${list} && rm -rf /var/lib/apt/lists/*`
    case "apk":
      return `apk add --no-cache ${list}`
    case "dnf":
      return `dnf install -y ${list} && dnf clean all`
  }
}

function envLine(env: Record<string, string>): string | undefined {
  const entries = Object.entries(env)
  if (entries.length === 0) return undefined
  const pairs = entries.map(([key, value]) => {
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)) throw new Pi2Error(`invalid image env name "${key}"`)
    return `${key}=${JSON.stringify(value).replaceAll("$", "\\$")}`
  })
  return `ENV ${pairs.join(" ")}`
}

/** `RUN` step for a user command; newlines become line continuations. */
function runLine(command: string): string {
  return `RUN ${command.trim().replaceAll(/\s*\n\s*/g, " \\\n    ")}`
}

export function renderDockerfile(config: Config, piVersion: string): string {
  const { image } = config
  const manager = image.packageManager ?? detectPackageManager(image.base)
  const systemPackages = [...new Set(["git", "ca-certificates", ...image.systemPackages])]
  const lines = [
    "# Generated by pi2. Do not edit.",
    `FROM ${image.base}`,
    "USER root",
    `ENV PI_CODING_AGENT_DIR=${AGENT_DIR} PI_CODING_AGENT_SESSION_DIR=${SESSIONS_DIR} HOME=${HOME_DIR} NPM_CONFIG_UPDATE_NOTIFIER=false`,
    `RUN mkdir -p ${AGENT_DIR} ${SESSIONS_DIR} ${HOME_DIR} ${WORKSPACE_DIR}`,
    `RUN ${installPackages(manager, systemPackages)}`,
    `RUN command -v npm >/dev/null || { echo "pi2: base image must provide node and npm" >&2; exit 1; }; npm install -g ${shQuote(`${PI_PACKAGE}@${piVersion}`)} && npm cache clean --force`,
    ...image.commands.map(runLine),
    ...config.packages.map((source) => `RUN pi install ${shQuote(source)}`),
    envLine(image.env),
    `RUN chmod -R a+rwX /opt/pi2 ${HOME_DIR} ${WORKSPACE_DIR}`,
    `WORKDIR ${WORKSPACE_DIR}`,
    `CMD ["sleep", "infinity"]`,
  ]
  return `${lines.filter((line) => line !== undefined).join("\n")}\n`
}

export function imageTag(dockerfile: string): string {
  return `pi2:${shortHash(dockerfile)}`
}
